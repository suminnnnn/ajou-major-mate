from typing import List, Dict
import json
import os
import re
import time
from langchain_openai import ChatOpenAI

llm = ChatOpenAI(
        model="gpt-4o",
        temperature=0,
        openai_api_key=os.getenv("OPENAI_API_KEY")
    )

MAX_RETRY = 2

EVAL_PROMPT_TEMPLATE = """
You are an impartial and rigorous evaluator following the 'LLM-as-a-Judge' methodology.

Your task is to assess the quality of the **answer** generated by a language model, given the original user query and the supporting context.
    
Evaluate the answer based on the following four criteria. For each criterion:
- Give a score from 0 (poor) to 5 (excellent)
- Provide a concise but rigorous comment in Korean. Be critical: even small factual or completeness issues should reduce the score.

### Evaluation Criteria:

1. **Goal Alignment**
   - Does the answer fully address the user’s intent and satisfy the goal of the query?

2. **Factual Accuracy**
   - Are all factual statements correct?
   - Is the answer free of hallucinations or misleading content?

3. **Completeness**
   - Does the answer include all essential information and cover all relevant aspects?
   - Is anything important missing or insufficiently addressed?

4. **Expression Quality**
   - Is the language clear, well-structured, and fluent?
   - Is the tone appropriate for an informational assistant?

---

Return the result as a JSON object in **exactly** the following format (no extra text):

```json
{{
  "Goal Alignment": {{ "score": 0-5, "comment": "..." }},
  "Factual Accuracy": {{ "score": 0-5, "comment": "..." }},
  "Completeness": {{ "score": 0-5, "comment": "..." }},
  "Expression Quality": {{ "score": 0-5, "comment": "..." }}
}}

### User Query:
{query}

### Answer:
{answer}    

### Context:
{context}
"""

def evaluate_response_with_llm(query: str, answer: str, context_docs: List[str]) -> Dict:
    prompt = EVAL_PROMPT_TEMPLATE.format(
        query=query.strip(),
        answer=answer.strip(),
        context="\n".join(context_docs).strip()
    )

    def extract_json(text: str) -> str:
        return re.sub(r"```json|```", "", text).strip()

    required_keys = ["Goal Alignment", "Factual Accuracy", "Completeness", "Expression Quality"]

    for attempt in range(MAX_RETRY + 1):
        try:
            response = llm.invoke(prompt)
            parsed = json.loads(extract_json(response))
            if all(k in parsed for k in required_keys): 
                return parsed
        except Exception as e:
            if attempt == MAX_RETRY:
                return {
                    "error": f"Parsing failed after {MAX_RETRY + 1} attempts: {str(e)}",
                    **{k: {"score": 0, "comment": "Evaluation failed."} for k in required_keys}
                }
            time.sleep(0.3)
